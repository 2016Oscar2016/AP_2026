// macros.h – власний заголовочний файл: макроси
#pragma once

#define ABS(x)    ((x) < 0 ? -(x) : (x))        // макрос – модуль числа
#define SQR(x)    ((x) * (x))                   // макрос з параметром – квадрат числа
#define CUBE(x)   ((x) * (x) * (x))             // куб числа
#define MAX(a, b) ((a) > (b) ? (a) : (b))       // макрос – найбільше з двох чисел
#define MIN(a, b) ((a) < (b) ? (a) : (b))       // макрос – найменше з двох чисел

                                                // виведення повідомлення та значення дійсного числа
#define PRINTR(w) puts("result :"); \
        printf(#w "=%f\n", (double)(w))

#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

#include "macros.h"                 // макроси винесено у власний файл macros.h

/*  Якщо потрібно, щоб макроси були у цьому файлі:
    закоментувати рядок  #include "macros.h"  і розкоментувати блок нижче

#define ABS(x)    ((x) < 0 ? -(x) : (x))        // макрос – модуль числа
#define SQR(x)    ((x) * (x))                   // макрос з параметром – квадрат числа
#define CUBE(x)   ((x) * (x) * (x))             // куб числа
#define MAX(a, b) ((a) > (b) ? (a) : (b))       // макрос – найбільше з двох чисел
#define MIN(a, b) ((a) < (b) ? (a) : (b))       // макрос – найменше з двох чисел

                                                // виведення повідомлення та значення дійсного числа
#define PRINTR(w) puts("result :"); \
        printf(#w "=%f\n", (double)(w))
*/

#define Z 2                         // директива препроцесора – значення z (ціле)

int main()
{
    double x, y, w;                 // змінні для розрахунків

    puts("Input x, y");
    scanf("%lf", &x);               // введення чисел
    scanf("%lf", &y);

#if Z > 1 && Z < 3                  // якщо умова істинна, то 1 < z < 3
    w = MAX(ABS(x) + ABS(y) + ABS(Z), CUBE(x));
    PRINTR(w);                      // макрос виведення результату
#elif Z > 3                         // компілювати іншу частину програми, якщо z > 3
    w = MIN(2 * x + y, SQR(2 * y - Z));
    PRINTR(w);
#else                               // z <= 1 або z = 3
    puts("w is not defined");
#endif                              // завершення блоку умовної компіляції

    return 0;
}
